// Builds worker/worker.js: the JiranLink AI server for Cloudflare Workers.
// It bakes in the same prompts and tools the app uses (src/ai/spec.ts), so the two never drift apart.
// Run: npm run build:worker   then paste worker/worker.js into the Cloudflare editor (or `wrangler deploy`).

import { mkdirSync, writeFileSync } from "node:fs";
import { AGENT_PROMPT, AGENT_TOOLS, CLASSIFY_PROMPT, DEFAULT_GEMINI_MODEL, FALLBACK_GEMINI_MODEL } from "../src/ai/spec";

const core = `// JiranLink AI server. Generated by scripts/build-worker.ts from src/ai/spec.ts. Do not edit by hand.
//
// Holds the Gemini API key so the website never does. Runs on Vercel (api/, region pinned in vercel.json) or as a
// Cloudflare Worker (worker/worker.js). Set these as environment variables / secrets:
//   GEMINI_API_KEY   (Secret, required)
//   GEMINI_MODEL     (optional, default ${DEFAULT_GEMINI_MODEL})
//   ALLOWED_ORIGINS  (optional, comma-separated; default the GitHub Pages site and local dev)
//
// Endpoints:
//   GET  /check     opens in a browser: confirms the key and model work  (on Vercel: /api/check, etc.)
//   POST /classify  { text }       -> { content }   search fallback: picks service categories
//   POST /agent     { contents }   -> { content }   "Ask JiranLink" assistant turn with tool calling

const DEFAULT_MODEL = ${JSON.stringify(DEFAULT_GEMINI_MODEL)};
const FALLBACK_MODEL = ${JSON.stringify(FALLBACK_GEMINI_MODEL)};
const DEFAULT_ORIGINS = ["https://hengchuanquah.github.io", "http://localhost:5173", "http://localhost:4173", "http://localhost:4174"];

const CLASSIFY_PROMPT = ${JSON.stringify(CLASSIFY_PROMPT)};
const AGENT_PROMPT = ${JSON.stringify(AGENT_PROMPT)};
const AGENT_TOOLS = ${JSON.stringify(AGENT_TOOLS)};

// Best-effort limits. Each Cloudflare location keeps its own counts, so treat them as a brake, not a wall.
const PER_IP_LIMIT = 60;            // requests per IP per window
const WINDOW_MS = 10 * 60 * 1000;   // 10 minutes
const DAILY_LIMIT = 2000;           // requests per day for this Worker instance
const hits = new Map();
let day = { date: "", count: 0 };

function limited(ip) {
  const now = Date.now();
  const today = new Date().toISOString().slice(0, 10);
  if (day.date !== today) day = { date: today, count: 0 };
  if (++day.count > DAILY_LIMIT) return "The AI has reached today's limit. Try again tomorrow.";
  const h = hits.get(ip) ?? { start: now, n: 0 };
  if (now - h.start > WINDOW_MS) { h.start = now; h.n = 0; }
  h.n++;
  hits.set(ip, h);
  if (hits.size > 5000) hits.clear();
  return h.n > PER_IP_LIMIT ? "Too many questions in a short time. Please wait a few minutes." : null;
}

function cors(origin, env) {
  const allowed = (env.ALLOWED_ORIGINS ? env.ALLOWED_ORIGINS.split(",").map((s) => s.trim()) : DEFAULT_ORIGINS);
  return {
    "Access-Control-Allow-Origin": allowed.includes(origin) ? origin : allowed[0],
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Max-Age": "86400",
    "Vary": "Origin",
  };
}

// Which Cloudflare data centre and visitor country handled the request (for diagnosing region blocks).
const where = (request) => {
  if (request.cf) return (request.cf.colo || "?") + " data centre, visitor in " + (request.cf.country || "?");
  const region = typeof process !== "undefined" && process.env ? process.env.VERCEL_REGION : "";
  return (region || "?") + " region, visitor in " + (request.headers.get("x-vercel-ip-country") || "?");
};

const json = (body, status, headers) => new Response(JSON.stringify(body), { status, headers: { ...headers, "Content-Type": "application/json" } });

// Only pass through the parts Gemini needs, with size caps, so the server can't be used as a general chatbot.
function cleanContents(contents) {
  if (!Array.isArray(contents) || contents.length === 0 || contents.length > 16) throw new Error("Invalid conversation.");
  return contents.map((c) => {
    if (!c || (c.role !== "user" && c.role !== "model") || !Array.isArray(c.parts) || c.parts.length > 8) throw new Error("Invalid message.");
    return {
      role: c.role,
      parts: c.parts.map((p) => {
        const out = {};
        if (typeof p.text === "string") {
          if (c.role === "user" && p.text.length > 600) throw new Error("Message too long.");
          out.text = p.text.slice(0, 4000);
        }
        if (p.functionCall && typeof p.functionCall.name === "string") out.functionCall = { name: p.functionCall.name, args: p.functionCall.args ?? {} };
        if (p.functionResponse && typeof p.functionResponse.name === "string") {
          if (JSON.stringify(p.functionResponse.response ?? {}).length > 8000) throw new Error("Tool result too large.");
          out.functionResponse = { name: p.functionResponse.name, response: p.functionResponse.response ?? {} };
        }
        if (typeof p.thoughtSignature === "string") out.thoughtSignature = p.thoughtSignature;
        return out;
      }),
    };
  });
}

// Models that were busy recently are skipped for a while, so every call doesn't fail on them first.
// Each server instance keeps its own memory; that's good enough to cut most wasted attempts.
const BUSY_MS = 5 * 60 * 1000;
// A single Gemini call that runs past this is abandoned and the next model is tried.
const CALL_LIMIT_MS = 12000;
const busyUntil = {};
// Lowest documented "thinking" level per model (Gemini docs); flash-lite already defaults to its lowest.
const THINKING = { "gemini-3.8-flash": "low" };

function withThinking(body, model) {
  const level = THINKING[model];
  if (!level) return body;
  return { ...body, generationConfig: { ...(body.generationConfig || {}), thinkingConfig: { thinkingLevel: level } } };
}

/** prefer: "lite" puts the lighter, faster model first (used by the assistant).
 *  trace (optional array) collects every attempt: model, HTTP status, milliseconds. */
async function gemini(env, body, prefer, trace = []) {
  // The assistant always tries the lighter model first, even when GEMINI_MODEL names a bigger one: speed matters more there.
  const main = env.GEMINI_MODEL || DEFAULT_MODEL;
  let models = prefer === "lite" ? [FALLBACK_MODEL, main] : [main, FALLBACK_MODEL];
  models = models.filter((m, i) => models.indexOf(m) === i);
  const now = Date.now();
  const fresh = models.filter((m) => !(busyUntil[m] > now));
  if (fresh.length) models = [...fresh, ...models.filter((m) => !fresh.includes(m))].slice(0, models.length);
  let last = "", lastStatus = 502;
  for (const model of models) {
    let thinking = true;
    // Busy (500/503): wait briefly and retry once. Busy again, out of quota (429) or unavailable: next model.
    for (let attempt = 0; attempt < 3; attempt++) {
      const t0 = Date.now();
      let res;
      try {
        res = await fetch("https://generativelanguage.googleapis.com/v1beta/models/" + encodeURIComponent(model) + ":generateContent", {
          method: "POST",
          headers: { "Content-Type": "application/json", "x-goog-api-key": env.GEMINI_API_KEY },
          body: JSON.stringify(thinking ? withThinking(body, model) : body),
          signal: AbortSignal.timeout(CALL_LIMIT_MS),
        });
      } catch (e) {
        const slow = e && (e.name === "TimeoutError" || e.name === "AbortError");
        trace.push({ model, status: slow ? "timeout" : "network", ms: Date.now() - t0 });
        // Too slow: skip this model for a while. A network error: just try the next model.
        if (slow) busyUntil[model] = Date.now() + BUSY_MS;
        last = slow ? "Gemini " + model + " took longer than " + CALL_LIMIT_MS / 1000 + " s." : "Could not reach Gemini (" + (e && e.message) + ").";
        lastStatus = slow ? 504 : 502;
        break;
      }
      const data = await res.json().catch(() => ({}));
      trace.push({ model, status: res.status, ms: Date.now() - t0 });
      if (res.ok) {
        const content = data?.candidates?.[0]?.content;
        if (!content) throw Object.assign(new Error("Gemini returned no answer (" + (data?.candidates?.[0]?.finishReason || data?.promptFeedback?.blockReason || "empty") + ")."), { status: 502 });
        return { content: { role: "model", parts: content.parts ?? [] }, model };
      }
      last = "Gemini error " + res.status + ": " + (data?.error?.message || "").slice(0, 200);
      lastStatus = res.status === 429 ? 429 : res.status === 503 || res.status === 500 ? 503 : 502;
      // If this model rejects the thinking setting, try once more without it.
      if (res.status === 400 && thinking && THINKING[model] && /thinking/i.test(last)) { thinking = false; continue; }
      const busy = res.status === 500 || res.status === 503;
      if (busy && attempt === 0) { await new Promise((r) => setTimeout(r, 800)); continue; }
      if (busy || res.status === 429) busyUntil[model] = Date.now() + BUSY_MS;
      // Model not offered to this key: skip it for a day instead of failing on it every time.
      if (res.status === 404 || res.status === 403 || (res.status === 400 && /model/i.test(last))) busyUntil[model] = Date.now() + 24 * 3600 * 1000;
      const tryNext = busy || res.status === 429 || res.status === 404 || res.status === 403 || (res.status === 400 && /model/i.test(last));
      if (tryNext) break;
      throw Object.assign(new Error(last), { status: lastStatus });
    }
  }
  throw Object.assign(new Error(last || "No Gemini model available."), { status: lastStatus });
}

async function handle(request, env) {
  {
    const url = new URL(request.url);
    // Last path segment: "/check" on Cloudflare, "/api/check" on Vercel.
    const route = url.pathname.split("/").filter(Boolean).pop() || "check";
    const origin = request.headers.get("Origin") || "";
    const headers = cors(origin, env);
    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers });
    if (!env.GEMINI_API_KEY) return json({ error: "The AI server has no GEMINI_API_KEY yet. Add it in the hosting settings and redeploy." }, 500, headers);

    const ip = request.headers.get("CF-Connecting-IP") || (request.headers.get("x-forwarded-for") || "").split(",")[0].trim() || "unknown";
    const tooMany = limited(ip);
    if (tooMany) return json({ error: tooMany }, 429, headers);

    try {
      if (request.method === "GET" && route === "check" && url.searchParams.get("agent")) {
        // Timing test for the assistant: one agent turn on a short message, with every attempt timed.
        const trace = [];
        const t0 = Date.now();
        const msg = String(url.searchParams.get("agent")).slice(0, 80);
        try {
          const r = await gemini(env, {
            systemInstruction: { parts: [{ text: AGENT_PROMPT }] },
            tools: [{ functionDeclarations: AGENT_TOOLS }],
            contents: [{ role: "user", parts: [{ text: msg }] }],
          }, "lite", trace);
          const parts = r.content.parts || [];
          return json({ ok: true, message: msg, model: r.model, totalMs: Date.now() - t0, attempts: trace,
            reply: parts.map((p) => p.text || (p.functionCall ? "[tool " + p.functionCall.name + "]" : "")).join(""), ranFrom: where(request) }, 200, headers);
        } catch (e) {
          return json({ ok: false, message: msg, totalMs: Date.now() - t0, attempts: trace, error: e.message, ranFrom: where(request) }, 200, headers);
        }
      }

      if (request.method === "GET" && route === "check") {
        const r = await gemini(env, {
          systemInstruction: { parts: [{ text: CLASSIFY_PROMPT }] },
          contents: [{ role: "user", parts: [{ text: "aircond bocor air" }] }],
          generationConfig: { responseMimeType: "application/json" },
        });
        const answer = (r.content.parts || []).map((p) => p.text || "").join("");
        return json({ ok: true, model: r.model, test: "aircond bocor air", answer, ranFrom: where(request) }, 200, headers);
      }

      if (request.method !== "POST") return json({ error: "Not found." }, 404, headers);
      const allowed = (env.ALLOWED_ORIGINS ? env.ALLOWED_ORIGINS.split(",").map((s) => s.trim()) : DEFAULT_ORIGINS);
      if (!allowed.includes(origin)) return json({ error: "This AI server only answers the JiranLink website." }, 403, headers);
      const raw = await request.text();
      if (raw.length > 40000) return json({ error: "Request too large." }, 413, headers);
      const body = JSON.parse(raw || "{}");

      if (route === "classify") {
        const text = String(body.text || "").trim();
        if (!text || text.length > 300) return json({ error: "Text must be 1 to 300 characters." }, 400, headers);
        const r = await gemini(env, {
          systemInstruction: { parts: [{ text: CLASSIFY_PROMPT }] },
          contents: [{ role: "user", parts: [{ text }] }],
          generationConfig: { responseMimeType: "application/json" },
        });
        return json({ content: r.content, model: r.model }, 200, headers);
      }

      if (route === "agent") {
        const trace = [];
        const r = await gemini(env, {
          systemInstruction: { parts: [{ text: AGENT_PROMPT }] },
          tools: [{ functionDeclarations: AGENT_TOOLS }],
          contents: cleanContents(body.contents),
        }, "lite", trace);
        return json({ content: r.content, model: r.model, attempts: trace }, 200, headers);
      }

      return json({ error: "Not found." }, 404, headers);
    } catch (e) {
      const msg = e.message || "AI server error.";
      const hint = /location is not supported/i.test(msg)
        ? " Google blocked the server location this ran from (" + where(request) + "). Host the AI server in a supported region (see README)."
        : "";
      return json({ error: msg + hint, ranFrom: where(request) }, e.status || 400, headers);
    }
  }
}
`;

// Cloudflare Worker: one file to paste into the dashboard.
const worker = core + "\nexport default { fetch: (request, env) => handle(request, env) };\n";
mkdirSync(new URL("../worker", import.meta.url), { recursive: true });
writeFileSync(new URL("../worker/worker.js", import.meta.url), worker);

// Vercel: shared core plus one small file per route. vercel.json pins the region to Singapore.
const core2 = core + "\nexport { handle };\n";
mkdirSync(new URL("../api", import.meta.url), { recursive: true });
writeFileSync(new URL("../api/_core.js", import.meta.url), core2);
for (const route of ["check", "classify", "agent"]) {
  writeFileSync(
    new URL(`../api/${route}.js`, import.meta.url),
    `// Generated by scripts/build-worker.ts. Vercel route /api/${route}.\nimport { handle } from "./_core.js";\nconst run = (request) => handle(request, process.env);\nexport { run as GET, run as POST, run as OPTIONS };\n`,
  );
}
console.log(`wrote worker/worker.js and api/*.js (${(core.length / 1024).toFixed(1)} KB core)`);
