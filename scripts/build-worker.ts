// Builds worker/worker.js: the JiranLink AI server for Cloudflare Workers.
// It bakes in the same prompts and tools the app uses (src/ai/spec.ts), so the two never drift apart.
// Run: npm run build:worker   then paste worker/worker.js into the Cloudflare editor (or `wrangler deploy`).

import { mkdirSync, writeFileSync } from "node:fs";
import { AGENT_PROMPT, AGENT_TOOLS, CLASSIFY_PROMPT, DEFAULT_GEMINI_MODEL, FALLBACK_GEMINI_MODEL } from "../src/ai/spec";

const worker = `// JiranLink AI server (Cloudflare Worker). Generated by scripts/build-worker.ts. Do not edit by hand.
//
// Holds the Gemini API key so the website never does. Set these in the Worker's Settings > Variables and Secrets:
//   GEMINI_API_KEY   (Secret, required)
//   GEMINI_MODEL     (optional, default ${DEFAULT_GEMINI_MODEL})
//   ALLOWED_ORIGINS  (optional, comma-separated; default the GitHub Pages site and local dev)
//
// Endpoints:
//   GET  /check     opens in a browser: confirms the key and model work
//   POST /classify  { text }       -> { content }   search fallback: picks service categories
//   POST /agent     { contents }   -> { content }   "Ask JiranLink" assistant turn with tool calling

const DEFAULT_MODEL = ${JSON.stringify(DEFAULT_GEMINI_MODEL)};
const FALLBACK_MODEL = ${JSON.stringify(FALLBACK_GEMINI_MODEL)};
const DEFAULT_ORIGINS = ["https://hengchuanquah.github.io", "http://localhost:5173", "http://localhost:4173", "http://localhost:4174"];

const CLASSIFY_PROMPT = ${JSON.stringify(CLASSIFY_PROMPT)};
const AGENT_PROMPT = ${JSON.stringify(AGENT_PROMPT)};
const AGENT_TOOLS = ${JSON.stringify(AGENT_TOOLS)};

// Best-effort limits. Each Cloudflare location keeps its own counts, so treat them as a brake, not a wall.
const PER_IP_LIMIT = 60;            // requests per IP per window
const WINDOW_MS = 10 * 60 * 1000;   // 10 minutes
const DAILY_LIMIT = 2000;           // requests per day for this Worker instance
const hits = new Map();
let day = { date: "", count: 0 };

function limited(ip) {
  const now = Date.now();
  const today = new Date().toISOString().slice(0, 10);
  if (day.date !== today) day = { date: today, count: 0 };
  if (++day.count > DAILY_LIMIT) return "The AI has reached today's limit. Try again tomorrow.";
  const h = hits.get(ip) ?? { start: now, n: 0 };
  if (now - h.start > WINDOW_MS) { h.start = now; h.n = 0; }
  h.n++;
  hits.set(ip, h);
  if (hits.size > 5000) hits.clear();
  return h.n > PER_IP_LIMIT ? "Too many questions in a short time. Please wait a few minutes." : null;
}

function cors(origin, env) {
  const allowed = (env.ALLOWED_ORIGINS ? env.ALLOWED_ORIGINS.split(",").map((s) => s.trim()) : DEFAULT_ORIGINS);
  return {
    "Access-Control-Allow-Origin": allowed.includes(origin) ? origin : allowed[0],
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Access-Control-Max-Age": "86400",
    "Vary": "Origin",
  };
}

// Which Cloudflare data centre and visitor country handled the request (for diagnosing region blocks).
const where = (request) => (request.cf ? (request.cf.colo || "?") + " data centre, visitor in " + (request.cf.country || "?") : "unknown");

const json = (body, status, headers) => new Response(JSON.stringify(body), { status, headers: { ...headers, "Content-Type": "application/json" } });

// Only pass through the parts Gemini needs, with size caps, so the server can't be used as a general chatbot.
function cleanContents(contents) {
  if (!Array.isArray(contents) || contents.length === 0 || contents.length > 16) throw new Error("Invalid conversation.");
  return contents.map((c) => {
    if (!c || (c.role !== "user" && c.role !== "model") || !Array.isArray(c.parts) || c.parts.length > 8) throw new Error("Invalid message.");
    return {
      role: c.role,
      parts: c.parts.map((p) => {
        const out = {};
        if (typeof p.text === "string") {
          if (c.role === "user" && p.text.length > 600) throw new Error("Message too long.");
          out.text = p.text.slice(0, 4000);
        }
        if (p.functionCall && typeof p.functionCall.name === "string") out.functionCall = { name: p.functionCall.name, args: p.functionCall.args ?? {} };
        if (p.functionResponse && typeof p.functionResponse.name === "string") {
          if (JSON.stringify(p.functionResponse.response ?? {}).length > 8000) throw new Error("Tool result too large.");
          out.functionResponse = { name: p.functionResponse.name, response: p.functionResponse.response ?? {} };
        }
        if (typeof p.thoughtSignature === "string") out.thoughtSignature = p.thoughtSignature;
        return out;
      }),
    };
  });
}

async function gemini(env, body) {
  const models = [env.GEMINI_MODEL || DEFAULT_MODEL];
  if (!env.GEMINI_MODEL) models.push(FALLBACK_MODEL);
  let last = "";
  for (const model of models) {
    const res = await fetch("https://generativelanguage.googleapis.com/v1beta/models/" + encodeURIComponent(model) + ":generateContent", {
      method: "POST",
      headers: { "Content-Type": "application/json", "x-goog-api-key": env.GEMINI_API_KEY },
      body: JSON.stringify(body),
    });
    const data = await res.json().catch(() => ({}));
    if (res.ok) {
      const content = data?.candidates?.[0]?.content;
      if (!content) throw Object.assign(new Error("Gemini returned no answer (" + (data?.candidates?.[0]?.finishReason || data?.promptFeedback?.blockReason || "empty") + ")."), { status: 502 });
      return { content: { role: "model", parts: content.parts ?? [] }, model };
    }
    last = (data?.error?.message || "").slice(0, 200);
    // Try the fallback model only when this model is unknown or not available to this key.
    if (res.status === 404 || (res.status === 400 && /model/i.test(last)) || res.status === 403) continue;
    throw Object.assign(new Error("Gemini error " + res.status + ": " + last), { status: res.status === 429 ? 429 : 502 });
  }
  throw Object.assign(new Error("No Gemini model available to this key: " + last), { status: 502 });
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const origin = request.headers.get("Origin") || "";
    const headers = cors(origin, env);
    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers });
    if (!env.GEMINI_API_KEY) return json({ error: "The AI server has no GEMINI_API_KEY secret yet." }, 500, headers);

    const ip = request.headers.get("CF-Connecting-IP") || "unknown";
    const tooMany = limited(ip);
    if (tooMany) return json({ error: tooMany }, 429, headers);

    try {
      if (request.method === "GET" && (url.pathname === "/" || url.pathname === "/check")) {
        const r = await gemini(env, {
          systemInstruction: { parts: [{ text: CLASSIFY_PROMPT }] },
          contents: [{ role: "user", parts: [{ text: "aircond bocor air" }] }],
          generationConfig: { responseMimeType: "application/json" },
        });
        const answer = (r.content.parts || []).map((p) => p.text || "").join("");
        return json({ ok: true, model: r.model, test: "aircond bocor air", answer, ranFrom: where(request) }, 200, headers);
      }

      if (request.method !== "POST") return json({ error: "Not found." }, 404, headers);
      const allowed = (env.ALLOWED_ORIGINS ? env.ALLOWED_ORIGINS.split(",").map((s) => s.trim()) : DEFAULT_ORIGINS);
      if (!allowed.includes(origin)) return json({ error: "This AI server only answers the JiranLink website." }, 403, headers);
      const raw = await request.text();
      if (raw.length > 40000) return json({ error: "Request too large." }, 413, headers);
      const body = JSON.parse(raw || "{}");

      if (url.pathname === "/classify") {
        const text = String(body.text || "").trim();
        if (!text || text.length > 300) return json({ error: "Text must be 1 to 300 characters." }, 400, headers);
        const r = await gemini(env, {
          systemInstruction: { parts: [{ text: CLASSIFY_PROMPT }] },
          contents: [{ role: "user", parts: [{ text }] }],
          generationConfig: { responseMimeType: "application/json" },
        });
        return json({ content: r.content, model: r.model }, 200, headers);
      }

      if (url.pathname === "/agent") {
        const r = await gemini(env, {
          systemInstruction: { parts: [{ text: AGENT_PROMPT }] },
          tools: [{ functionDeclarations: AGENT_TOOLS }],
          contents: cleanContents(body.contents),
        });
        return json({ content: r.content, model: r.model }, 200, headers);
      }

      return json({ error: "Not found." }, 404, headers);
    } catch (e) {
      const msg = e.message || "AI server error.";
      const hint = /location is not supported/i.test(msg)
        ? " Google blocked the Cloudflare data centre this ran from (" + where(request) + "). Turn off any VPN and try again, or turn on Smart Placement in the Worker's settings."
        : "";
      return json({ error: msg + hint, ranFrom: where(request) }, e.status || 400, headers);
    }
  },
};
`;

mkdirSync(new URL("../worker", import.meta.url), { recursive: true });
writeFileSync(new URL("../worker/worker.js", import.meta.url), worker);
console.log(`wrote worker/worker.js (${(worker.length / 1024).toFixed(1)} KB)`);
