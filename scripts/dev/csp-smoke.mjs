import { chromium } from "@playwright/test";
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = [];
p.on("pageerror", (e) => errs.push("pageerror " + e.message));
p.on("console", (m) => m.type() === "error" && !/Content Security Policy|ERR_|Failed to load/.test(m.text()) && errs.push(m.text()));
await p.goto("file://" + process.argv[2]);
await p.waitForSelector(".hero", { timeout: 8000 });
await p.locator("form.search-pill input").first().fill("tukang paip sinki tersumbat");
await p.keyboard.press("Enter");
await p.waitForSelector(".pcard");
await p.locator(".seg button", { hasText: "Map" }).click();
await p.waitForTimeout(2000);
await p.screenshot({ path: process.argv[3] });
await p.locator(".pcard").first().click();
await p.locator(".svc-row button", { hasText: "Book" }).first().click();
await p.locator(".slot-btn:not([disabled])").first().click();
await p.locator("button", { hasText: "Send request for" }).click();
await p.waitForSelector(".status");
console.log(errs.length ? errs.join("\n") : "CSP smoke OK");
await b.close();
